const lazyFlags = new Map<string, TSVGIconComponent>();

export const getLazyCountryFlag = (code: string): TSVGIconComponent | undefined => {
  const load = FLAG_LOADERS[code];
  if (!load) return undefined;

  const cached = lazyFlags.get(code);
  if (cached) return cached;

  const Flag = lazy(load);
  const LazyFlag = (props: ISVGIconProps): ReactElement => (
    <Suspense
      fallback={
        <span className={classNames('svg-icon', { [`svg-icon__size-${props.size}`]: props.size }, props.className)} />
      }
    >
      <Flag {...props} />
    </Suspense>
  );
  LazyFlag.displayName = `LazyFlag(${code})`;

  lazyFlags.set(code, LazyFlag);
  return LazyFlag;
};
